// Zero-dependency bundler for the browser page.
//
// The physics/engine modules are plain ESM with only relative imports and
// `export` statements, so a tiny inliner is enough: walk the import graph from
// the browser entry, concatenate each module once in dependency order, and
// strip import/export keywords. The result is one classic script that runs from
// file:// directly and from GitHub Pages with no build toolchain or dependency.
// The src/ ESM files remain the single source of truth used by Node tests.
//
// Run:  node scripts/build-site.mjs

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src', 'browser-main.js');
const outFile = join(root, 'examples', 'site', 'game.bundle.js');

const visited = new Set();
const ordered = [];

function load(modulePath) {
  if (visited.has(modulePath)) return;
  visited.add(modulePath);
  let source = readFileSync(modulePath, 'utf8');
  const importPaths = [];

  // import ... from './x.js';  (default, namespace, and named forms)
  source = source.replace(
    /import\s+(?:[\w*{},\s]+\s+from\s+)?['"]([^'"]+)['"];?/g,
    (m, spec) => {
      importPaths.push(spec);
      return '';
    },
  );

  // Recurse into dependencies BEFORE registering this module, so dependencies
  // appear earlier in the concatenated output.
  for (const spec of importPaths) {
    if (!spec.startsWith('.')) {
      throw new Error(`browser bundle only supports relative imports, got: ${spec}`);
    }
    load(resolve(dirname(modulePath), spec));
  }

  // Strip export keywords; declarations stay in shared scope of the IIFE.
  source = source
    .replace(/export\s+default\s+/g, '')
    .replace(/export\s+(const|let|var|function|class)\s+/g, '$1 ')
    .replace(/export\s*\{[^}]*\};?/g, '');

  ordered.push(`// --- module: ${modulePath.replace(root, '.').replace(/\\/g, '/')} ---\n${source}`);
}

load(entry);

const banner = `// Generated by scripts/build-site.mjs — do not edit by hand.
// Source of truth: the ESM modules under src/. Re-run the build after changes.
`;
const bundle = `${banner}(function () {\n'use strict';\n\n${ordered.join('\n\n')}\n})();\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, bundle);
console.log(`bundled ${visited.size} modules -> ${outFile.replace(root, '.').replace(/\\/g, '/')} (${bundle.length} bytes)`);
