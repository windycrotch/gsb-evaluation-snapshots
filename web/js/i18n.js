const LANGS = ["de", "en"];
let lang = "en";
const subs = new Set();

function detect() {
  try {
    const saved = localStorage.getItem("impasto.lang");
    if (LANGS.includes(saved)) return saved;
  } catch {}
  const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
  return nav === "de" ? "de" : "en";
}

export function getLang() { return lang; }

export function t(key, vars) {
  let s = TEXT[lang]?.[key];
  if (s === undefined) s = EN[key] !== undefined ? EN[key] : DE[key] !== undefined ? DE[key] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : ""));
  return s;
}

export function applyStatic(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-tip]")) el.dataset.tip = t(el.dataset.i18nTip);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  document.title = t("app.title");
}

export function setLang(l) {
  if (!LANGS.includes(l)) l = "en";
  lang = l;
  try { localStorage.setItem("impasto.lang", l); } catch {}
  document.documentElement.lang = l;
  applyStatic();
  for (const fn of subs) { try { fn(l); } catch (e) { console.error(e); } }
}

export function onLang(fn) { subs.add(fn); }

export function initLang() {
  lang = detect();
  document.documentElement.lang = lang;
  return lang;
}
